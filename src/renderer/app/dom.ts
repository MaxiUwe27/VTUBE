// Tiny DOM helpers – declarative element construction without a framework.

export type Child = Node | string | number | null | undefined | false;
export type Children = (Child | Child[])[];

type Props = Record<string, unknown> & {
  class?: string;
  style?: Partial<CSSStyleDeclaration> | string;
  dataset?: Record<string, string>;
};

// Attributes that must go through setAttribute (read-only or non-reflected properties).
const ATTR_ONLY = new Set(['list', 'for', 'role', 'viewBox', 'd', 'fill', 'stroke']);

export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  props?: Props | null,
  ...children: Children
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  if (props) applyProps(el, props);
  append(el, children);
  return el;
}

export function applyProps(el: HTMLElement, props: Props): void {
  for (const [k, v] of Object.entries(props)) {
    if (v === undefined || v === null || v === false) continue;
    if (k === 'class') el.className = String(v);
    else if (k === 'style') {
      if (typeof v === 'string') el.setAttribute('style', v);
      else Object.assign(el.style, v);
    } else if (k === 'dataset') Object.assign(el.dataset, v);
    else if (k.startsWith('on') && typeof v === 'function') {
      el.addEventListener(k.slice(2).toLowerCase(), v as EventListener);
    } else if (ATTR_ONLY.has(k) || k.startsWith('aria-') || k.startsWith('data-') || !(k in el)) {
      el.setAttribute(k, v === true ? '' : String(v));
    } else {
      (el as unknown as Record<string, unknown>)[k] = v;
    }
  }
}

export function append(el: Node, children: Children): void {
  for (const c of children.flat()) {
    if (c === null || c === undefined || c === false) continue;
    el.appendChild(typeof c === 'string' || typeof c === 'number' ? document.createTextNode(String(c)) : c);
  }
}

/** Replace all children of `el`. */
export function setChildren(el: Node, ...children: Children): void {
  while (el.firstChild) el.removeChild(el.firstChild);
  append(el, children);
}

/** Set textContent only when it changed (avoids layout churn in live meters). */
export function setText(el: Node, text: string): void {
  if (el.textContent !== text) el.textContent = text;
}

export function toggleClass(el: Element, cls: string, on: boolean): void {
  if (el.classList.contains(cls) !== on) el.classList.toggle(cls, on);
}

